import assert from 'node:assert/strict';
import {planInterruption} from './lib/interruption.ts';
import {DEFAULT,issues} from './lib/time.ts';
const added={id:'unexpected',name:'Unexpected call',category:'Personal',start:1000,end:1015,reminders:[]};
const before=JSON.stringify(DEFAULT);
const shifted=planInterruption(DEFAULT,'default-9',added,true);
assert.equal(JSON.stringify(DEFAULT),before);
assert.equal(shifted.activities.find(a=>a.id==='default-9').end,1000);
assert.equal(shifted.activities.find(a=>a.id===shifted.resumeId).start,1015);
assert.equal(shifted.activities.find(a=>a.id===shifted.resumeId).end,1125);
assert.equal(shifted.activities.find(a=>a.id==='default-10').start,1125);
assert.ok(DEFAULT.every(a=>shifted.activities.some(b=>b.id===a.id)));
const kept=planInterruption(DEFAULT,'default-9',added,false);
assert.equal(kept.activities.find(a=>a.id==='default-10').start,1110);
assert.ok(issues(kept.activities).some(s=>s.startsWith('Overlap')));
const boundary=planInterruption(DEFAULT,'default-9',{...added,start:990,end:1005},true);
assert.equal(boundary.activities.some(a=>a.id==='default-9'),false);
assert.equal(boundary.activities.find(a=>a.id===boundary.resumeId).end,1125);
assert.throws(()=>planInterruption(DEFAULT,'default-12',{...added,start:1430,end:1450},false),/midnight/);
assert.throws(()=>planInterruption(DEFAULT,'default-9',{...added,name:' '},true),/name/);
assert.throws(()=>planInterruption(DEFAULT,'default-9',{...added,end:1000.5},true),/duration/);
console.log('Passed: split and resume, preserve remainder, shift later times, keep and flag overlaps, immutable preview, exact activity boundary, invalid input and midnight guard.');
